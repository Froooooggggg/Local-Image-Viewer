/// **首次启动**的免责声明确认弹窗。
///
/// 与设置页里的"查看完整免责声明"不同：这个是启动时的强制确认，
/// 只有"同意并继续"一个出口（系统返回键等同不同意，会退出应用）。
///
/// 返回 true 表示用户已同意。
Future<bool> showFirstRunDisclaimer(BuildContext context) async {
  final agreed = await showDialog<bool>(
    context: context,
    barrierDismissible: false,
    builder: (ctx) => PopScope(
      // 不能靠返回键跳过：不同意就不该进入使用。
      canPop: false,
      child: AlertDialog(
        title: const Text('使用前请阅读'),
        content: const SizedBox(
          width: 420,
          child: SingleChildScrollView(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              mainAxisSize: MainAxisSize.min,
              children: [
                Text(
                  '简易图集查看器是一个本地只读工具。'
                  '首次使用前，请确认你已了解以下内容。',
                  style: TextStyle(fontSize: 12.5, height: 1.6),
                ),
                SizedBox(height: 14),
                DisclaimerText(full: true),
              ],
            ),
          ),
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(ctx, false),
            child: const Text('不同意'),
          ),
          FilledButton(
            onPressed: () => Navigator.pop(ctx, true),
            child: const Text('同意并继续'),
          ),
        ],
      ),
    ),
  );
  return agreed ?? false;
}
